export function tocLabel(text: string): string {
  const full = text.trim()
  if (labels[full]) return labels[full]
  const parts = full.split(/\s[—–]\s/)
  if (parts.length > 1) return /^(phase|fase)\s*\d/i.test(parts[0]) ? parts[1] : parts[0]
  return full
}
